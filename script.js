document.addEventListener('DOMContentLoaded', () => {

  /* ---- Scroll reveal: fade/slide/scale elements in as they enter the
     viewport. Direction comes from data-reveal="up|down|left|right|scale",
     stagger from data-reveal-delay="<ms>" (see styles.css). ---- */
  const revealEls = document.querySelectorAll('[data-reveal]');
  if (revealEls.length) {
    revealEls.forEach(el => {
      const delay = el.getAttribute('data-reveal-delay');
      if (delay) el.style.setProperty('--reveal-delay', `${delay}ms`);
    });

    if ('IntersectionObserver' in window) {
      const revealObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
          if (!entry.isIntersecting) return;
          entry.target.classList.add('is-visible');
          revealObserver.unobserve(entry.target);
        });
      }, { threshold: 0.15, rootMargin: '0px 0px -8% 0px' });
      revealEls.forEach(el => revealObserver.observe(el));
    } else {
      revealEls.forEach(el => el.classList.add('is-visible'));
    }
  }

  /* ---- Filmstrip marquee: pull the 2 most recently uploaded photos per
     category from Supabase (same 'photos' table as the gallery), build
     frames, duplicate set for seamless loop. ---- */
  const scribbleOverlay = `
    <svg class="scribble" viewBox="0 0 200 60" preserveAspectRatio="none" aria-hidden="true">
      <path d="M4 30 C 40 8, 70 50, 110 22 S 170 44, 196 18" stroke="currentColor" stroke-width="3" fill="none" stroke-linecap="round"/>
    </svg>`;
  const scribbleFrames = new Set([1, 4]);

  const track = document.getElementById('filmstrip-track');
  if (track && window.supabase && window.RC_SUPABASE_URL) {
    (async () => {
      const client = window.supabase.createClient(window.RC_SUPABASE_URL, window.RC_SUPABASE_PUBLISHABLE_KEY);
      const { data, error } = await client
        .from('photos')
        .select('image_url, alt_text, category, created_at')
        .order('created_at', { ascending: false });

      if (error) {
        console.error('Failed to load filmstrip photos:', error.message);
        return;
      }
      if (!data || !data.length) return;

      // Keep the 2 most recent uploads per category (data is already sorted
      // newest-first), ordered to match RC_PHOTO_CATEGORIES / the gallery
      // filter buttons.
      const byCategory = new Map();
      data.forEach((photo) => {
        const list = byCategory.get(photo.category) || [];
        if (list.length < 2) list.push(photo);
        byCategory.set(photo.category, list);
      });
      const categoryOrder = (window.RC_PHOTO_CATEGORIES || []).map(c => c.value);
      const filmstripPhotos = categoryOrder.flatMap(cat => byCategory.get(cat) || []);
      if (!filmstripPhotos.length) return;

      const buildFrame = (photo, i) => {
        const frame = document.createElement('a');
        frame.href = `/gallery?filter=${encodeURIComponent(photo.category)}`;
        frame.className = 'filmstrip-frame';

        const img = document.createElement('img');
        // A 110px-wide frame does not need the 2000px original — pulling those
        // meant ~2.7 MB before a single frame appeared, so the strip sat black
        // for seconds on a phone.
        img.src = window.RC_THUMB ? window.RC_THUMB(photo.image_url, 340) : photo.image_url;
        img.alt = photo.alt_text || 'Photography highlight';
        // Deliberately not lazy: the marquee moves frames into view with a CSS
        // transform, which does not re-trigger lazy loading, so the duplicated
        // half of the strip stayed permanently blank. The duplicates reuse the
        // first half's URLs, so this costs no extra requests.
        img.decoding = 'async';
        // Fade each frame in as it decodes, so a slow connection shows the
        // black film base filling in rather than empty holes.
        img.addEventListener('load', () => frame.classList.add('is-loaded'));
        img.addEventListener('error', () => {
          if (img.src !== photo.image_url) img.src = photo.image_url; // transform failed
          else frame.classList.add('is-loaded');
        });
        frame.appendChild(img);

        if (scribbleFrames.has(i)) frame.insertAdjacentHTML('beforeend', scribbleOverlay);
        return frame;
      };

      const frag = document.createDocumentFragment();
      [...filmstripPhotos, ...filmstripPhotos].forEach((photo, i) => {
        frag.appendChild(buildFrame(photo, i % filmstripPhotos.length));
      });
      track.innerHTML = '';
      track.appendChild(frag);
    })();
  }

  /* ---- Footer ticker: duplicate content for seamless loop ---- */
  const star = `<svg class="star" viewBox="0 0 24 24" width="12" height="12" aria-hidden="true"><path d="M12 0 L14 10 L24 12 L14 14 L12 24 L10 14 L0 12 L10 10 Z" fill="currentColor"/></svg>`;
  const tickerTrack = document.getElementById('ticker-track');
  const renderTicker = (lang) => {
    if (!tickerTrack) return;
    const tickerText = translations[lang].ticker;
    const buildTicker = () => Array.from({ length: 6 }, (_, i) =>
      `<span class="ticker-item">${tickerText[i % 2]} ${star}</span>`
    ).join('');
    tickerTrack.innerHTML = buildTicker() + buildTicker();
  };

  /* ---- Language switch ---- */
  const langButtons = document.querySelectorAll('.lang-btn');
  const i18nElements = document.querySelectorAll('[data-i18n]');
  const setLanguage = (lang) => {
    const dict = translations[lang];
    i18nElements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });
    langButtons.forEach(btn => {
      const isActive = btn.dataset.lang === lang;
      btn.classList.toggle('active', isActive);
      btn.setAttribute('aria-pressed', String(isActive));
    });
    document.documentElement.lang = lang;
    renderTicker(lang);
    localStorage.setItem('rc-lang', lang);
  };

  langButtons.forEach(btn => {
    btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
  });

  const savedLang = localStorage.getItem('rc-lang');
  setLanguage(savedLang === 'sr' ? 'sr' : 'en');

  /* ---- Before / after compare slider ---- */
  const compareSlider = document.getElementById('compare-slider');
  const compareBefore = document.getElementById('compare-before');
  const compareHandle = document.getElementById('compare-handle');

  if (compareSlider && compareBefore && compareHandle) {
    let dragging = false;

    const setComparePosition = (clientX) => {
      const rect = compareSlider.getBoundingClientRect();
      let percent = ((clientX - rect.left) / rect.width) * 100;
      percent = Math.min(100, Math.max(0, percent));
      compareBefore.style.clipPath = `inset(0 ${100 - percent}% 0 0)`;
      compareHandle.style.left = `${percent}%`;
      compareHandle.setAttribute('aria-valuenow', String(Math.round(percent)));
    };

    compareHandle.addEventListener('pointerdown', (e) => {
      dragging = true;
      compareHandle.setPointerCapture(e.pointerId);
    });
    compareHandle.addEventListener('pointermove', (e) => {
      if (dragging) setComparePosition(e.clientX);
    });
    compareHandle.addEventListener('pointerup', () => { dragging = false; });
    compareHandle.addEventListener('pointercancel', () => { dragging = false; });

    compareSlider.addEventListener('pointerdown', (e) => {
      if (e.target === compareHandle || compareHandle.contains(e.target)) return;
      setComparePosition(e.clientX);
    });

    compareHandle.addEventListener('keydown', (e) => {
      const current = parseFloat(compareHandle.style.left) || 50;
      if (e.key === 'ArrowLeft') setComparePosition(compareSlider.getBoundingClientRect().left + (compareSlider.getBoundingClientRect().width * (current - 4) / 100));
      if (e.key === 'ArrowRight') setComparePosition(compareSlider.getBoundingClientRect().left + (compareSlider.getBoundingClientRect().width * (current + 4) / 100));
    });
  }

  /* ---- Gallery filter + lightbox ----
     Gallery items are loaded asynchronously from Supabase by gallery-loader.js,
     so this only runs once they're actually in the DOM (see 'rc:gallery-loaded'
     listener at the bottom of this block) instead of at DOMContentLoaded time. */
  function initGallery() {
  const filterButtons = document.querySelectorAll('.filter-btn');
  const galleryItems = document.querySelectorAll('.gallery-item');
  const galleryEmpty = document.getElementById('gallery-empty');

  /* ---- Entrance animation: items fly in from alternating sides, both the
     first time they scroll into view and again on every filter switch. ---- */
  const primeGalleryItem = (item, i) => {
    item.style.setProperty('--gi-tx', i % 2 === 0 ? '-70px' : '70px');
    item.style.setProperty('--gi-delay', `${Math.min(i, 9) * 55}ms`);
  };
  const playEntrance = (item) => {
    item.classList.remove('is-visible');
    void item.offsetWidth; // force reflow so the transition restarts
    item.classList.add('is-visible');
  };

  let galleryRevealObserver = null;
  if (galleryItems.length) {
    galleryItems.forEach((item, i) => primeGalleryItem(item, i));

    if ('IntersectionObserver' in window) {
      galleryRevealObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
          if (!entry.isIntersecting) return;
          entry.target.classList.add('is-visible');
          galleryRevealObserver.unobserve(entry.target);
        });
      }, { threshold: 0.1, rootMargin: '0px 0px -6% 0px' });
      galleryItems.forEach(item => galleryRevealObserver.observe(item));
    } else {
      galleryItems.forEach(item => item.classList.add('is-visible'));
    }
  }

  if (filterButtons.length && galleryItems.length) {
    filterButtons.forEach(btn => {
      btn.addEventListener('click', () => {
        filterButtons.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        const filter = btn.dataset.filter;
        let visibleCount = 0;
        let visibleIndex = 0;
        galleryItems.forEach(item => {
          const match = filter === 'all' || item.dataset.category === filter;
          item.style.display = match ? '' : 'none';
          if (match) {
            visibleCount++;
            if (galleryRevealObserver) galleryRevealObserver.unobserve(item);
            primeGalleryItem(item, visibleIndex);
            playEntrance(item);
            visibleIndex++;
          }
        });
        if (galleryEmpty) galleryEmpty.style.display = visibleCount === 0 ? 'block' : 'none';
      });
    });

    // Deep-link from the homepage filmstrip: ?filter=<category>
    const requestedFilter = new URLSearchParams(window.location.search).get('filter');
    if (requestedFilter) {
      const targetBtn = Array.from(filterButtons).find(b => b.dataset.filter === requestedFilter);
      if (targetBtn) {
        targetBtn.click();
        document.getElementById('gallery-filters')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    }
  }

  /* ---- Gallery lightbox ---- */
  const lightbox = document.getElementById('lightbox');
  const lightboxImg = document.getElementById('lightbox-img');
  const lightboxCaption = document.getElementById('lightbox-caption');
  const lightboxClose = document.getElementById('lightbox-close');
  const lightboxPrev = document.getElementById('lightbox-prev');
  const lightboxNext = document.getElementById('lightbox-next');

  if (lightbox && galleryItems.length) {
    let currentIndex = 0;
    let visibleItems = [];

    const getVisibleItems = () => Array.from(galleryItems).filter(item => item.style.display !== 'none');

    const showLightboxAt = (index) => {
      if (!visibleItems.length) return;
      currentIndex = (index + visibleItems.length) % visibleItems.length;
      const item = visibleItems[currentIndex];
      const img = item.querySelector('img');
      const caption = item.querySelector('figcaption');
      // The grid holds a thumbnail; open the full-size original here.
      lightboxImg.src = item.dataset.full || img.src;
      lightboxImg.alt = img.alt;
      lightboxCaption.textContent = caption
        ? `${caption.textContent} — ${currentIndex + 1} / ${visibleItems.length}`
        : `${currentIndex + 1} / ${visibleItems.length}`;
    };

    const openLightbox = (item) => {
      visibleItems = getVisibleItems();
      const index = visibleItems.indexOf(item);
      showLightboxAt(index === -1 ? 0 : index);
      lightbox.classList.add('open');
      document.body.classList.add('lightbox-open');
      document.dispatchEvent(new CustomEvent('rc:lightbox-open'));
    };

    const closeLightbox = () => {
      lightbox.classList.remove('open');
      document.body.classList.remove('lightbox-open');
    };

    galleryItems.forEach(item => {
      item.addEventListener('click', () => openLightbox(item));
    });

    lightboxClose.addEventListener('click', closeLightbox);
    lightbox.addEventListener('click', (e) => {
      if (e.target === lightbox) closeLightbox();
    });
    lightboxPrev.addEventListener('click', () => showLightboxAt(currentIndex - 1));
    lightboxNext.addEventListener('click', () => showLightboxAt(currentIndex + 1));

    document.addEventListener('keydown', (e) => {
      if (!lightbox.classList.contains('open')) return;
      if (e.key === 'Escape') closeLightbox();
      if (e.key === 'ArrowLeft') showLightboxAt(currentIndex - 1);
      if (e.key === 'ArrowRight') showLightboxAt(currentIndex + 1);
    });
  }
  }

  document.addEventListener('rc:gallery-loaded', initGallery);

  /* ---- Mobile hamburger menu ---- */
  const header = document.querySelector('.site-header');
  const hamburger = document.getElementById('hamburger');
  hamburger.addEventListener('click', () => {
    const isOpen = header.classList.toggle('nav-open');
    hamburger.classList.toggle('open', isOpen);
    hamburger.setAttribute('aria-expanded', String(isOpen));
  });

  document.querySelectorAll('.main-nav a').forEach(link => {
    link.addEventListener('click', () => {
      header.classList.remove('nav-open');
      hamburger.classList.remove('open');
      hamburger.setAttribute('aria-expanded', 'false');
    });
  });
});
